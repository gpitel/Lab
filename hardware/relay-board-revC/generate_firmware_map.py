"""
Generate firmware/include/relay_map_revc.h from the rev C relay map.

    python generate_firmware_map.py

The relay words the firmware applies for CONF:MEAS / CAL:MODE are computed
here by scripts/RelayMapRevC.py from the configuration table in
scripts/RelayBoardController.py -- the same code verify_board.py simulates
over the netlist -- so the C tables cannot drift from what was verified.
The GPIO order comes from generate_schematic.GPIO_PINS.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "scripts"))
import RelayBoardController as rbc  # noqa: E402
import RelayMapRevC as b2             # noqa: E402

DESTINATION = os.path.join(HERE, "..", "..", "firmware", "include", "relay_map_revc.h")


def gpio_pins():
    """GPIO_PINS from generate_schematic.py without importing kicad-sch-api."""
    text = open(os.path.join(HERE, "generate_schematic.py"), encoding="utf-8").read()
    block = re.search(r"GPIO_PINS = \[(.*?)\]", text, re.S).group(1)
    return re.findall(r'"(P[ABCF]\d+)"', block)


#: firmware port index per GPIO letter (relay_port() in firmware/src/main.c)
PORT_INDEX = {"A": 0, "B": 1, "C": 2, "F": 3}


def gpio_code(pin):
    return 16 * PORT_INDEX[pin[1]] + int(pin[2:])


def words(function):
    return [function(rbc.CONFIGS[number]) for number in sorted(rbc.CONFIGS)]


def c_table(name, values, comment):
    lines = [f"/* {comment} */", f"#define {name} {{" + " \\"]
    for number, value in zip(sorted(rbc.CONFIGS), values):
        lines.append(f"    0x{value:06X}u, /* {number:2d} {rbc.CONFIGS[number]['name']} */ \\")
    lines.append("}")
    return "\n".join(lines)


def main():
    pins = gpio_pins()
    if len(pins) != b2.RELAY_COUNT:
        raise SystemExit(f"{len(pins)} GPIO pins for {b2.RELAY_COUNT} relays")
    meas = words(lambda c: b2.measurement_word(c))
    tables = {mode: words(lambda c, m=mode: b2.calibration_word(c, m)
                          if c["HI"] and c["LO"] else b2.measurement_word(c)
                          | sum(1 << bit for bit in b2.ISOLATE_BITS.values()))
              for mode in ("OPEN", "SHORT", "LOAD")}
    for word in meas + [w for t in tables.values() for w in t]:
        b2.check_budget(word | (1 << b2.KELVIN_TIE_BIT) | (1 << b2.CH1_KELVIN_BIT))
    kelvin = (1 << b2.KELVIN_TIE_BIT) | (1 << b2.CH1_KELVIN_BIT)
    gpio = ", ".join(f"{gpio_code(p)}u" for p in pins)
    text = f"""/*
 * Relay map for the OpenMagnetics relay board rev C (Kelvin crossbar).
 *
 * GENERATED by hardware/relay-board-revC/generate_firmware_map.py from
 * scripts/RelayMapRevC.py and the configuration table in
 * scripts/RelayBoardController.py -- do not edit. verify_board.py simulates
 * every one of these words over the exported netlist.
 *
 *   bit 0..7    crossbar  K1..K8    (A,B,C,D) x (HI, LO), pole 1 force / pole 2 sense
 *   bit 8,9     standards K9, K10   (standards column -> HI / LO)
 *   bit 10..13  isolation K11..K14  (energized = DUT out)
 *   bit 14..17  links     K15..K18  (A-B, C-D, B-C, B-D)
 *   bit 18..20  select    K19..K21  (100R LOAD, 1R check, 10 pF check)
 *   bit 21      K22 2-wire tie (energized = Kelvin)
 *   bit 22      K23 CH1 select (energized = Kelvin front-end)
 */

#ifndef RELAY_MAP_B2_H
#define RELAY_MAP_B2_H

#include <stdint.h>

#define BOARD_NAME "revC"
#define RELAY_COUNT {b2.RELAY_COUNT}u
#define CONFIG_COUNT {len(rbc.CONFIGS)}u
#define MAX_ENERGIZED {b2.MAX_ENERGIZED}u
#define MASK_KELVIN 0x{kelvin:06X}u
#define MASK_ISOLATION 0x{sum(1 << b for b in b2.ISOLATE_BITS.values()):06X}u

/* GPIO per relay K1..K{b2.RELAY_COUNT}: 16 * port + bit, port A=0, B=1, C=2, F=3. */
#define RELAY_GPIO_TABLE {{ {gpio} }}

{c_table("CONFIG_TABLE", meas, "CONF:MEAS words (2-wire; Kelvin ORs MASK_KELVIN)")}

{c_table("CAL_OPEN_TABLE", tables["OPEN"], "CAL:MODE OPEN words")}

{c_table("CAL_SHORT_TABLE", tables["SHORT"], "CAL:MODE SHORT words (first HI terminal's LO relay; exact Kelvin zero)")}

{c_table("CAL_LOAD_TABLE", tables["LOAD"], "CAL:MODE LOAD words (standards column, 100R selected)")}

typedef enum {{
    CAL_MODE_MEAS = 0,
    CAL_MODE_OPEN,
    CAL_MODE_SHORT,
    CAL_MODE_LOAD,
}} cal_mode_t;

#endif /* RELAY_MAP_B2_H */
"""
    with open(DESTINATION, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(f"wrote {os.path.normpath(DESTINATION)}: {b2.RELAY_COUNT} relays, "
          f"{len(rbc.CONFIGS)} configurations, GPIO {', '.join(pins)}")


if __name__ == "__main__":
    main()
